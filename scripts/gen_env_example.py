@dataclass(frozen=True)
class FieldDoc:
    name: str
    section: str | None
    comment: str


def parse_comments(source: str, class_name: str = "Settings") -> dict[str, FieldDoc]:
    """Field name -> (section header, trailing comment) from the Settings class source."""
    tree = ast.parse(source)
    cls = next(n for n in tree.body if isinstance(n, ast.ClassDef) and n.name == class_name)
    comments: dict[int, str] = {}
    full_line: dict[int, str] = {}
    for tok in tokenize.generate_tokens(io.StringIO(source).readline):
        if tok.type == tokenize.COMMENT:
            comments[tok.start[0]] = tok.string
            if not tok.line[: tok.start[1]].strip():
                full_line[tok.start[0]] = tok.string
    docs: dict[str, FieldDoc] = {}
    section: str | None = None
    prev_end = cls.lineno
    for node in cls.body:
        start = node.lineno
        for line in range(prev_end + 1, start):
            m = _SECTION_RE.match(full_line.get(line, ""))
            if m:
                section = m.group("title").strip()
        prev_end = node.end_lineno or start
        if isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
            end = node.end_lineno or start
            raw = next((comments[ln] for ln in range(end, start - 1, -1) if ln in comments and ln not in full_line), "")
            docs[node.target.id] = FieldDoc(node.target.id, section, raw.lstrip("#").strip())
    return docs


def _flatten(annotation: Any) -> list[Any]:
    origin = typing.get_origin(annotation)
    if origin in (typing.Union, types.UnionType):
        return [a for arg in typing.get_args(annotation) for a in _flatten(arg)]
    if origin is typing.Annotated:
        return _flatten(typing.get_args(annotation)[0])
    return [annotation]


def is_secret(annotation: Any) -> bool:
    """SecretStr or list[SecretStr] (possibly Optional / Annotated)."""
    for part in _flatten(annotation):
        if part is SecretStr:
            return True
        if typing.get_origin(part) in (list, tuple, set) and any(is_secret(a) for a in typing.get_args(part)):
            return True
    return False


def literal_options(annotation: Any) -> list[str]:
    for part in _flatten(annotation):
        if typing.get_origin(part) is typing.Literal:
            return [str(a) for a in typing.get_args(part)]
    return []


def default_of(field: FieldInfo) -> Any:
    if field.default is not PydanticUndefined:
        return field.default
    if field.default_factory is not None:
        return field.default_factory()  # type: ignore[call-arg]
    return None


def render_value(value: Any) -> str:
    """Environment-file representation of a default value."""
    if value is None:
        return ""
    if isinstance(value, SecretStr):
        return ""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, Path):
        try:
            return "./" + value.resolve().relative_to(ROOT).as_posix()
        except ValueError:
            return value.as_posix()
    if isinstance(value, list | tuple | set):
        return ",".join(render_value(v) for v in value)
    text = str(value)
    if re.search(r"[\s#'\"=]", text):
        return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'
    return text


