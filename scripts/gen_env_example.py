def describe(name: str, field: FieldInfo, doc: FieldDoc | None) -> str:
    """One comment line: the description followed by bracketed type hints."""
    text = (doc.comment if doc else "") or EXTRA_DESCRIPTIONS.get(name, "") or (field.description or "")
    hints: list[str] = []
    options = literal_options(field.annotation)
    if options:
        hints.append("options: " + " | ".join(options))
    elif bool in _flatten(field.annotation):
        hints.append("true/false")
    if is_secret(field.annotation):
        hints.append("secret")
    return " ".join([text.rstrip("."), *(f"[{h}]" for h in hints)]).strip()


def render(fields: dict[str, FieldInfo] | None = None, source: str | None = None) -> str:
    """The full .env.example text."""
    fields = fields if fields is not None else dict(config.Settings.model_fields)
    source = source if source is not None else CONFIG_SOURCE.read_text(encoding="utf-8")
    docs = parse_comments(source)
    lines = [HEADER.rstrip("\n")]
    current: str | None = object()  # type: ignore[assignment]  # sentinel: force the first header
    for name, field in fields.items():
        doc = docs.get(name)
        section = doc.section if doc else None
        if section != current:
            current = section
            title = section or "Other"
            lines += ["", f"# --- {title} " + "-" * max(3, 96 - len(title))]
        env = name.upper()
        text = describe(name, field, doc)
        if text:
            lines.append(f"# {text}")
        if is_secret(field.annotation):
            lines.append(f"{env}=")
        else:
            lines.append(f"# {env}={render_value(default_of(field))}")
    lines += ["", COMPOSE_SECTION.rstrip("\n")]
    return "\n".join(lines) + "\n"


def changed(path: Path, text: str) -> bool:
    return not path.is_file() or path.read_text(encoding="utf-8") != text


def main(argv: Iterable[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the file is out of date")
    parser.add_argument("--stdout", action="store_true", help="print instead of writing")
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args(list(argv) if argv is not None else None)
    text = render()
    if args.stdout:
        sys.stdout.write(text)
        return 0
    if args.check:
        if changed(args.output, text):
            print(f"{args.output.name} is out of date: run python scripts/gen_env_example.py")
            return 1
        print(f"{args.output.name} is up to date")
        return 0
    with args.output.open("w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print(f"wrote {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
