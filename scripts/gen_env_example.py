"""Generate ``.env.example`` from ``aadhi.config.Settings``.

    python scripts/gen_env_example.py            # rewrite .env.example
    python scripts/gen_env_example.py --check    # exit 1 if .env.example is out of date (CI)
    python scripts/gen_env_example.py --stdout   # print instead of writing

Names, defaults and types come from the pydantic model; descriptions come from the inline comments
and ``# --- Section ---`` headers in ``aadhi/config.py``. The Settings class is introspected, never
instantiated, so no ``.env`` file or environment value is read. Secrets are always emitted empty.
"""

