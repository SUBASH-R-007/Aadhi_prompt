def _plain(value: Any, where: str = "catalogue") -> Any:
    """``value`` as JSON data (mappings with string keys, lists, str, finite numbers, bool, None); ``TypeError`` for
    anything else, so a stray object can never be serialised by accident."""
    if value is None or isinstance(value, (bool, str)):
        return value
    if isinstance(value, int):
        return value
    if isinstance(value, float):
        if not math.isfinite(value):
            raise TypeError(f"{where}: non-finite number {value!r}")
        return value
    if isinstance(value, Mapping):
        out = {}
        for k, v in value.items():
            if not isinstance(k, str):
                raise TypeError(f"{where}: non-string key {k!r}")
            out[k] = _plain(v, f"{where}.{k}")
        return out
    if isinstance(value, (list, tuple)):
        return [_plain(v, f"{where}[{i}]") for i, v in enumerate(value)]
    raise TypeError(f"{where}: {type(value).__name__} is not catalogue data")


def _boxes(boxes: tuple[zn.Box, ...]) -> list[dict[str, int]]:
    return [b.as_dict() for b in boxes]


def _slot(s: tp.SlotSpec) -> dict[str, Any]:
    return {"w": s.w, "max_lines": s.max_lines, "size": list(s.size), "role": s.role, "face": s.face,
            "weight": s.weight, "line_height": s.line_height, "tracking_em": s.tracking_em, "max_words": s.max_words,
            "max_chars": s.max_chars, "prefer_lines": s.prefer_lines, "critical": s.critical,
            "tabular_nums": s.tabular_nums}


def _template(spec: tp.TemplateSpec) -> dict[str, Any]:
    return {
        "class": spec.semantic_class,
        "representational": spec.representational,
        "release": spec.release,
        "implemented": spec.implemented,
        "formats": list(spec.formats),
        "variants": {f: list(v) for f, v in spec.variants.items()},
        "forced_for": list(spec.forced_for),
        "duration": {f: {"min": d.min, "max": d.max, "per_item": d.per_item, "end_screen": d.end_screen}
                     for f, d in spec.duration.items()},
        "holds": list(spec.holds),
        "dense": spec.dense,
        "push_ok": spec.push_ok,
        "slots": {slot: {f: {v: _slot(s) for v, s in per_variant.items()} for f, per_variant in per_format.items()}
                  for slot, per_format in spec.slots.items()},
        "consumes": {"kinds": list(spec.consumes.kinds), "targets": list(spec.consumes.targets),
                     "forms": {k: list(spec.consumes.forms(k)) for k in spec.consumes.kinds}},
    }


def _platform(zone: zn.PlatformZone) -> dict[str, Any]:
    return {"top": zone.top, "bottom": zone.bottom, "left": zone.left, "right": zone.right,
            "rail": None if zone.rail is None else {"width": zone.rail.width, "from_y": zone.rail.from_y},
            "safe": _boxes(zone.safe_boxes())}


def _floors(f: zn.TypeFloors) -> dict[str, Any]:
    return {"text_min": f.text_min, "label_min": f.label_min, "body": list(f.body), "body_default": f.body_default,
            "heading": None if f.heading is None else list(f.heading),
            "display": None if f.display is None else list(f.display), "hook": None if f.hook is None else list(f.hook),
            "caption": list(f.caption), "caption_min": f.caption_min, "heavy_max_px": f.heavy_max_px,
            "heavy_min_weight": f.heavy_min_weight}


def _caption_style(style: th.CaptionStyle) -> dict[str, Any]:
    """A caption style: ``metrics``, its geometry (plan §1.1's caption-style metrics, the part the stage may read), and
    apart from it ``colours`` (for the gallery and the parity tests; the source scan keeps the stage from reading
    them, so the catalogue never decides a drawn colour)."""
    m = style.metrics
    metrics = None if m is None else {
        "padding_x": m.padding_x, "padding_y": m.padding_y, "radius_px": m.radius_px, "outline_px": m.outline_px,
        "word_spacing_em": m.word_spacing_em, "size": dict(m.size), "weight": dict(m.weight),
        "line_height": {f: dict(v) for f, v in m.line_height.items()}}
    colours = None if m is None else {
        "ink": m.ink, "backdrop": m.backdrop, "backdrop_alpha": m.backdrop_alpha, "outline": m.outline,
        "key_ink": m.key_ink}
    return {"release": style.release, "look": style.look, "metrics": metrics, "colours": colours}


def _family(f: th.Family) -> dict[str, Any]:
    return {"name": f.name, "mode": f.mode, "release": f.release, "hue": f.hue, "chroma": f.chroma,
            "windows": [list(w) for w in f.windows], "accent_period": f.accent_period, "personality": f.personality,
            "personality_target": f.personality_target, "tones": None if f.tones is None else list(f.tones),
            "slots": [th.scene_tokens(f, k) for k in range(f.accent_period)]}


def catalogue() -> dict[str, Any]:
    """The catalogue as plain data (the object ``CATALOGUE`` holds)."""
    formats = zn.FORMATS
    layout = zn.LAYOUT
    data = {
        "version": CATALOGUE_VERSION,
        "zones_version": zn.ZONES_VERSION,
        # exactly core.js's ZONES (format, width, height, critical, caption, header, title, body, textColumn)
        "zones": {f: zn.ZONES[f].as_stage_dict() for f in formats},
        "regions": {f: {name: box.as_dict() for name, box in zn.REGIONS[f].items()} for f in formats},
        "grid": {"landscape": {"box": zn.GRID.box.as_dict(), "columns": zn.GRID.columns, "gutter": zn.GRID.gutter,
                               "column_width": zn.GRID.column_width}},
        "end_screen": {"landscape": {"box": zn.END_SCREEN.box.as_dict(), "seconds": zn.END_SCREEN.seconds}},
        "platforms": {name: _platform(zone) for name, zone in zn.SAFE_ZONES.items()},
        "type": {
            "floors": {f: _floors(zn.TYPE_FLOORS[f]) for f in formats},
            "scale": {role: {"line_height": {s: list(v) for s, v in r.line_height.items()},
                             "tracking_em": list(r.tracking_em),
                             "max_line_chars": None if r.max_line_chars is None else dict(r.max_line_chars)}
                      for role, r in zn.TYPE_SCALE.items()},
            "caps": {"max_words": zn.CAPS_LABEL_MAX_WORDS, "tracking_em": list(zn.CAPS_TRACKING_EM)},
        },
        "layout": {
            "spacing": {"unit": layout.spacing_unit, "steps": list(layout.spacing)},
            "radius": dict(layout.radius), "border": dict(layout.border), "outline": dict(layout.outline),
            "shadow": dict(layout.shadow), "icon": dict(layout.icon),
            "alpha": {"dim": th.DIM_ALPHA, "scrim": th.SCRIM_ALPHA, "scrim_min": th.SCRIM_ALPHA_MIN,
                      "scrim_hex": th.SCRIM_ALPHA_HEX},
        },
        "captions": {sid: _caption_style(s) for sid, s in th.CAPTION_STYLES.items()},
        "cues": {mode: {"marker_ink": c.marker_ink, "marker_alpha": c.marker_alpha, "underline": c.underline}
                 for mode, c in th.CUE_COLOURS.items()},
        "templates": {tid: _template(spec) for tid, spec in tp.TEMPLATES.items()},
        "semantic_classes": {cid: {"claim": row.claim, "templates": list(row.templates)}
                             for cid, row in tp.SEMANTIC_CLASSES.items()},
        "targets": {"forms": list(tp.TARGET_FORMS), "reserved": sorted(tp.RESERVED_TARGET_WORDS)},
        "roles": {"colour": list(tp.ROLES), "block": list(tp.BLOCK_ROLES)},
        "backgrounds": {bid: {"release": b.release, "implemented": b.implemented,
                              "personalities": list(b.personalities), "block": b.block, "mirrored": b.mirrored}
                        for bid, b in tp.BACKGROUNDS.items()},
        "transitions": {tid: {"release": t.release, "implemented": t.implemented, "seconds": list(t.seconds)}
                        for tid, t in tp.TRANSITIONS.items()},
        "personalities": {pid: {"name": p.name, "release": p.release, "duration_scale": p.duration_scale,
                                "text_entrances": list(p.text_entrances), "icons_only": p.icons_only,
                                "transitions": list(p.transitions), "transitions_r1": list(p.transitions_r1),
                                "cue_term_style": p.cue_term_style, "caption_style": dict(p.caption_style),
                                "sfx_pack": p.sfx_pack, "music_mood": p.music_mood}
                          for pid, p in th.PERSONALITIES.items()},
        # {preset: {family: bool}} for the released families (themes.forced_scrims, §4.5)
        "scrims": th.forced_scrims(),
        # the Aadhi studio wall's surface token: B2f measures it (themes.STUDIO_WALL); null until then, never a guess
        "studio_surface": th.STUDIO_WALL,
        "families": {fid: _family(f) for fid, f in th.FAMILIES.items()},
        "content": {mode: th.content_tokens(mode) for mode in th.MODES},
    }
    if tuple(data) != TOP_LEVEL_KEYS:  # the declared shape (pinned by the shape test)
        raise AssertionError("catalogue top-level keys drifted from TOP_LEVEL_KEYS")
    return _plain(data)


WIDTH = 120  # the repository's line length


def _js(value: Any, indent: int, used: int) -> str:
    """``value`` as JSON (keys sorted) laid out for reading: on the current line when it fits in WIDTH with the
    ``used`` columns before it and a trailing comma, else one entry per line, ``indent`` + 2 spaces deep."""
    flat = json.dumps(value, ensure_ascii=False, allow_nan=False, sort_keys=True, separators=(", ", ": "))
    if not isinstance(value, (dict, list)) or not value or used + len(flat) + 1 <= WIDTH:
        return flat
    pad = " " * (indent + 2)
    if isinstance(value, dict):
        lines = []
        for key in sorted(value):
            head = f"{pad}{json.dumps(key, ensure_ascii=False)}: "
            lines.append(head + _js(value[key], indent + 2, len(head)))
        return "{\n" + ",\n".join(lines) + "\n" + " " * indent + "}"
    lines = [pad + _js(v, indent + 2, len(pad)) for v in value]
    return "[\n" + ",\n".join(lines) + "\n" + " " * indent + "]"


def render() -> str:
    """The text ``web/js/dynamic/catalogue.gen.js`` must hold."""
    opening = _PREAMBLE.rsplit("\n", 1)[1]  # "export const CATALOGUE = Object.freeze(freezeInside("
    return f"{_PREAMBLE}{_js(catalogue(), 0, len(opening))}{_POSTAMBLE}"


def first_difference(current: str | None, expected: str) -> int | None:
    """The 1-based line where ``current`` first differs from ``expected`` (None when equal; 1 when missing)."""
    if current == expected:
        return None
    if current is None:
        return 1
    a, b = current.split("\n"), expected.split("\n")
    for n, (x, y) in enumerate(zip(a, b, strict=False), start=1):
        if x != y:
            return n
    return min(len(a), len(b)) + 1


def read(path: Path = OUTPUT) -> str | None:
    """The file's text (exact bytes, UTF-8), or None when it is missing or unreadable."""
    try:
        return path.read_bytes().decode("utf-8")
    except (OSError, UnicodeDecodeError):
        return None


def write(path: Path = OUTPUT) -> bool:
    """Rewrite ``path`` when it differs; True when it was written."""
    text = render()
    if read(path) == text:
        return False
    path.write_bytes(text.encode("utf-8"))
    return True


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the generated file is out of date")
    parser.add_argument("--path", type=Path, default=OUTPUT, help=argparse.SUPPRESS)  # tests: check a copy
    args = parser.parse_args(argv)
    name = OUTPUT_NAME if args.path == OUTPUT else str(args.path)
    if args.check:
        line = first_difference(read(args.path), render())
        if line is None:
            return 0
        print(f"{name} is out of date (first difference at line {line}): run python -m aadhi.compose.dynamic.catalogue",
              file=sys.stderr)
        return 1
    if write(args.path):
        print(f"wrote {name}")
    return 0


