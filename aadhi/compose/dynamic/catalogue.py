"""Generate ``web/js/dynamic/catalogue.gen.js``, the Dynamic stage's catalogue (B2 plan §1.1; deviation register 1: it
replaces the design's ``web/dynamic/themes.json``, §4.7 / §10.3 B2).

    python -m aadhi.compose.dynamic.catalogue            # rewrite web/js/dynamic/catalogue.gen.js
    python -m aadhi.compose.dynamic.catalogue --check    # exit 1 when it is out of date (CI "Generated files")

The module is one ``export const CATALOGUE`` object, frozen all the way down, generated from ``zones.py`` (zones,
regions, grid, platform zones, type floors and scale, layout tokens), ``templates.py`` (the template registry, the
semantic classes, the target grammar, the colour roles, backgrounds, transitions) and ``themes.py`` (caption-style
metrics, cue colours, personalities, the forced-scrim table, families and content palettes, the alphas). Canonical
and byte-deterministic: keys sorted, lists in their declared order, numbers as Python's shortest round-trip repr
(which JavaScript parses to the same double), a value on one line when it fits in 120 columns, UTF-8, LF, one
trailing newline; a value that is not plain data fails generation. No float in it comes from a libm call (zones and
metrics are literals, tokens are rounded hex), so the bytes are the same on every platform.

**Runtime use is geometry only** (plan §1.1): the stage reads zones, regions, the grid, template slots, type floors,
layout tokens and caption-style metrics from it (core.js, from step B; the source scan's ``CATALOGUE_RUNTIME``).
Colours, durations and personality values reach the stage only through the timeline (``presentation.content``,
``look.tokens``, ...), so a stored timeline keeps its look when the catalogue changes (§6.7); families, content
palettes, cue colours, caption colours (beside each style's metrics), personalities and the scrims table are in it for
the gallery and the parity tests.
"""

