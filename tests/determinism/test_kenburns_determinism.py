"""Determinism of pictures on the real stage (DYNAMIC_VIDEO_DESIGN §7.4 test (a), §7.7): a still with Ken Burns
(``MediaRef.ken_burns``, which ``aadhi/compose/timeline.py`` attaches to AI-video fallback stills), a still shown
``contain_blur`` and a clip shown ``contain_blur`` (its pre-extracted frames, a new picture every frame) give identical
SHA-256 per captured frame (CDP JPEG q92, the production capture) whether the frames are rendered 1xN in order, as 3
chunks on three pages at once, or in reverse.

The B1 measurement behind the stage's "rising, never scaling" rule (board_generic.js) was that a picture drawn at a
changing scale could look different depending on the frames painted before it (Chromium keeps the decodes and mip
levels it has drawn a picture at). Ken Burns zooms the picture every frame, so it is checked here on its own: the
still is larger than its frame, so the zoom crosses the 50% scale at which Chromium switches mip level, and it has
a fine checkerboard, where a different resampling shows at once.

The stills and the clip's frames (JPEGs, like the worker's extraction) are deterministic pictures generated by the
test and served to the page through the worker's ``/__frames/`` route (``open_stage(frames=...)``), the same request
path the render worker answers media from. Like ``test_frame_hashes.py``, this is ``slow`` and ``container``: the
hashes are compared within one machine only.
"""

from __future__ import annotations

import io
import re
from collections.abc import Callable
from contextlib import asynccontextmanager
from typing import Any

import pytest

from aadhi.compose.dynamic.determinism import run_plans, standard_plans
from aadhi.compose.dynamic.stage_page import open_stage

pytestmark = [pytest.mark.slow, pytest.mark.container]
TOKEN = "determinism.pictures"
FPS = 30
SECONDS = 4.0
FRAMES = int(SECONDS * FPS)
STILL_PATH = "/__frames/test-still/kenburns.png"
WIDE_PATH = "/__frames/test-still/four-three.png"
# a clip's pre-extracted frame (web/js/dynamic/media.js frameUrl: /__frames/<mediaKey>/<n, 6 digits>.jpg)
CLIP_FRAME = re.compile(r"^/__frames/(v-[0-9a-f]{16}-(\d+)x(\d+))/(\d{6})\.jpg$")
CLIP_SIZE = (640, 480)  # the test clip's own size (4:3)
TOKENS = {"struct.accent": "#FF936D", "bg": "#10132C", "bg-alt": "#181D37", "bg-tint": "#22121C", "surface": "#252A3F"}
CONTENT = {"ink": "#F3F5F9", "ink2": "#B9BEC7", "entity:0": "#0FE3FE", "entity:1": "#C4A4FE", "entity:2": "#FEACE3",
           "warn": "#F8A87F", "ok": "#5DD8AA", "mark": "#F2D935", "focus": "#F2D935"}
# The shape aadhi.compose.timeline.ken_burns_for gives (scale 1.00-1.04 -> 1.12-1.20, a pan around the centre).
KEN_BURNS = {"start": {"cx": 0.46, "cy": 0.55, "scale": 1.02}, "end": {"cx": 0.56, "cy": 0.45, "scale": 1.18}}


def _still(width: int, height: int) -> bytes:
    """A deterministic PNG: colour gradients under a 3 px checkerboard and thin rings (resampling shows at once)."""
    np = pytest.importorskip("numpy")
    from PIL import Image, ImageDraw

    yy, xx = np.mgrid[0:height, 0:width]
    rgb = np.empty((height, width, 3), dtype=np.uint8)
    rgb[..., 0] = (xx * 255 // max(1, width - 1)).astype(np.uint8)
    rgb[..., 1] = (yy * 255 // max(1, height - 1)).astype(np.uint8)
    rgb[..., 2] = np.where(((xx // 3) + (yy // 3)) % 2 == 0, 40, 220).astype(np.uint8)
    im = Image.fromarray(rgb, "RGB")
    draw = ImageDraw.Draw(im)
    for k in range(1, 12):
        r = k * min(width, height) // 24
        draw.ellipse((width // 2 - r, height // 2 - r, width // 2 + r, height // 2 + r), outline=(255, 255, 255), width=2)
    buf = io.BytesIO()
    im.save(buf, format="PNG", optimize=False, compress_level=1)
    return buf.getvalue()


def _clip_frame(n: int, width: int, height: int) -> bytes:
    """Frame ``n`` of a deterministic test clip, a JPEG like the worker's extracted frames: the still's pattern with
    its colours shifted every frame and a bar that moves, so every frame, and its blurred backdrop, differs."""
    np = pytest.importorskip("numpy")
    from PIL import Image

    yy, xx = np.mgrid[0:height, 0:width]
    rgb = np.empty((height, width, 3), dtype=np.uint8)
    rgb[..., 0] = ((xx * 255 // max(1, width - 1) + 37 * n) % 256).astype(np.uint8)
    rgb[..., 1] = ((yy * 255 // max(1, height - 1) + 101 * n) % 256).astype(np.uint8)
    rgb[..., 2] = np.where(((xx // 3) + (yy // 3)) % 2 == 0, 40, 220).astype(np.uint8)
    x0 = (23 * n) % width
    rgb[:, x0:x0 + width // 8] = (255 * (n % 2), 255, 255 * ((n // 2) % 2))
    buf = io.BytesIO()
    Image.fromarray(rgb, "RGB").save(buf, format="JPEG", quality=90)
    return buf.getvalue()


def _timeline(fmt: str, media: dict[str, Any]) -> dict[str, Any]:
    """One AI-video scene (the board_generic ``media`` variant: the title over the picture's frame) of SECONDS."""
    portrait = fmt == "portrait"
    look = {"template": "board_generic", "tokens": dict(TOKENS),
            "background": {"preset": "mesh_drift", "params": {"tone": "bg"}, "seed": 11, "frozen_at": None},
            "transition_in": {"kind": "cut", "seconds": 0}}
    beat = {"beat_id": "k1", "index": 0, "start": 0.5, "speech_end": 3.5, "end": 3.6,
            "narration": "The river splits into many channels.",
            "captions": [{"start": 0.5, "end": 3.5, "text": "The river splits into many channels."}]}
    scene = {"scene_id": "still", "index": 0, "type": "ai_video", "title": "A river delta", "start": 0,
             "duration": SECONDS, "audio_offset": 0.5, "beats": [beat], "media": media, "look": look}
    return {
        "schema_version": 3, "language": "en-IN", "board_language": "en-IN", "fps": FPS,
        "width": 1080 if portrait else 1920, "height": 1920 if portrait else 1080, "total_duration": SECONDS,
        "chapters": [{"start": 0, "title": "Rivers"}], "captions": [], "transition_seconds": 0.4, "scenes": [scene],
        "presentation": {
            "style": "dynamic", "format": fmt, "safe_zone": "universal", "content": dict(CONTENT),
            "fonts": {"display": "outfit", "body": "inter", "mono": "jetbrains_mono"}, "personality": "crisp",
            "caption_style": "clean_pill", "cue_term_style": "underline", "captions_burn": False, "sfx": False,
            "motion": "standard", "generated_seconds": SECONDS, "engine_version": 1,
        },
    }


async def _assert_order_independent(real_app, served: dict[str, Any], serve: Callable[[str], bytes | None]) -> Any:
    requested: list[str] = []
    unknown: set[str] = set()

    def frames(path: str) -> bytes | None:
        requested.append(path)
        found = serve(path)
        if found is None:
            unknown.add(path)
        return found

    @asynccontextmanager
    async def open_page():
        async with open_stage(real_app.settings, size=(served["width"], served["height"]), token=TOKEN,
                              base_url=real_app.base, served_timeline=served, frames=frames) as page:
            yield page

    report = await run_plans(open_page, standard_plans(0, FRAMES, 3))
    assert not unknown, f"the page asked for media the test does not serve: {sorted(unknown)[:5]}"
    assert requested, "the media was never requested: it is not on the page"
    mismatches = report.mismatches()
    assert mismatches == [], f"{len(mismatches)} of {FRAMES} frames differ by render order, first: {mismatches[:3]}"
    assert report.guard_trips == [] and report.errors == [], (report.guard_trips, report.errors)
    assert report.distinct_frames() > FRAMES // 2, "the picture should move every frame"
    return report


@pytest.mark.parametrize("fmt", ["landscape", "portrait"])
async def test_ken_burns_still_frames_are_identical_in_any_order(real_app, fmt: str) -> None:
    # 2400 x 1350 in a frame of about 1120 x 630 (16:9) or 960 x 540 (9:16): the zoom (1.02 -> 1.18) draws it at
    # 47-55% (16:9), across the 50% mip boundary, and at 40-47% (9:16)
    files = {STILL_PATH: _still(2400, 1350)}
    media = {"kind": "image", "asset_key": "still-kb", "url": STILL_PATH, "width": 2400, "height": 1350, "fit": "cover",
             "ken_burns": KEN_BURNS}
    await _assert_order_independent(real_app, _timeline(fmt, media), files.get)


@pytest.mark.parametrize("fmt", ["landscape", "portrait"])
async def test_contain_blur_still_frames_are_identical_in_any_order(real_app, fmt: str) -> None:
    # a 4:3 still without declared dimensions: board_generic gives it a 16:9 frame, so `contain_blur` shows the
    # blurred backdrop at both sides; with Ken Burns on the contained picture (B2 full_bleed_media in 9:16)
    files = {WIDE_PATH: _still(1600, 1200)}
    media = {"kind": "image", "asset_key": "still-blur", "url": WIDE_PATH, "fit": "contain_blur", "ken_burns": KEN_BURNS}
