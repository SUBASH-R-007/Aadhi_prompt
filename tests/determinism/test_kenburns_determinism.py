_CLIP_JS = """() => {
  const c = document.querySelector('.dyn-media-backdrop');
  const r = document.querySelector('.dyn-frame').getBoundingClientRect();
  return { shown: getComputedStyle(c).display !== 'none', width: c.width,
           layer: getComputedStyle(c.parentElement).willChange, frame: [r.width, r.height] };
}"""


@pytest.mark.parametrize("fmt", ["landscape", "portrait"])
@pytest.mark.parametrize("sized", [False, True], ids=["backdrop-shown", "frame-fits-clip"])
async def test_contain_blur_clip_frames_are_identical_in_any_order(real_app, fmt: str, sized: bool) -> None:
    # A 4:3 clip shown contain_blur the way the render page shows clips: an <img> of the worker's pre-extracted frame,
    # a new src every frame. Every frame has its own colours.
    # * backdrop-shown: the clip's size unknown, board_generic gives it a 16:9 frame and the backdrop shows at its
    #   sides, drawn from the frame. Drawn from the picture shown before (while a new src loads Chromium keeps
    #   reporting the old picture's size: media.js waits for img.complete), it would differ between the forward order
    #   (the next frames prefetched, LOOKAHEAD) and the reverse one (each frame loaded afresh). The backdrop canvas is
    #   a composited layer, and so is the clip above it: without the layer dynamic.css gives the box around both
    #   (.dyn-media--clip), 93 of 120 16:9 frames differed by order (17 of 120 in 9:16, the clip covering it).
    # * frame-fits-clip: its size known, the frame takes its aspect and the clip covers it: no backdrop at all
    #   (media.js backdropShown).
    served_frames: dict[str, bytes] = {}

    def serve(path: str) -> bytes | None:
        m = CLIP_FRAME.match(path)
        if m is None:
            return None
        if path not in served_frames:
            # the worker's extraction: the clip scaled to cover the planned size, aspect kept (encode.extract_args)
            k = max(int(m[2]) / CLIP_SIZE[0], int(m[3]) / CLIP_SIZE[1])
            served_frames[path] = _clip_frame(int(m[4]), 2 * round(CLIP_SIZE[0] * k / 2), 2 * round(CLIP_SIZE[1] * k / 2))
        return served_frames[path]

    media: dict[str, Any] = {"kind": "video", "asset_key": "clip-blur", "url": "/media/clip-blur.mp4",
                             "duration": SECONDS, "src_fps": FPS, "end_behavior": "freeze", "fit": "contain_blur"}
    if sized:
        media.update(width=CLIP_SIZE[0], height=CLIP_SIZE[1])
    served = _timeline(fmt, media)
    await _assert_order_independent(real_app, served, serve)
    keys = {m[1] for m in map(CLIP_FRAME.match, served_frames) if m}
    assert len(keys) == 1, f"one clip at one size in every chunk (mediaPlan): {keys}"
    shown = sorted(int(m[4]) for m in map(CLIP_FRAME.match, served_frames) if m)
    assert shown[0] == 0 and shown[-1] == FRAMES - 1, "frame n of the clip for frame n of the scene (src_fps = fps)"
    async with open_stage(real_app.settings, size=(served["width"], served["height"]), token=TOKEN,
                          base_url=real_app.base, served_timeline=served, frames=serve) as page:
        await page.seek(2 * FPS)
        got = await page.page.evaluate(_CLIP_JS)
    w, h = got["frame"]
    assert got["shown"] is (not sized), got
    assert got["layer"] == "transform", "a contain_blur clip's box has a layer of its own (dynamic.css)"
    if sized:
        assert abs(w / h - CLIP_SIZE[0] / CLIP_SIZE[1]) < 0.01, "the frame takes the clip's aspect"
    else:
        assert abs(w / h - 16 / 9) < 0.01 and got["width"] == 64, "a 16:9 frame, its backdrop drawn"


_BACKDROP_JS = """() => {
  const c = document.querySelector('.dyn-media-backdrop');
  if (!c) return null;
  const media = c.parentElement;
  const d = c.getContext('2d').getImageData(0, 0, c.width, c.height).data;
  let opaque = 0;
  let lo = 255;
  let hi = 0;
  for (let i = 0; i < d.length; i += 4) {
    if (d[i + 3] === 255) opaque += 1;
    const l = (d[i] + d[i + 1] + d[i + 2]) / 3;
    lo = Math.min(lo, l);
    hi = Math.max(hi, l);
  }
  const rect = (e) => { const r = e.getBoundingClientRect(); return [r.left, r.top, r.width, r.height]; };
  return { size: [c.width, c.height], pixels: d.length / 4, opaque, lo, hi, canvas: rect(c), media: rect(media),
           order: [...media.children].map((e) => e.tagName),
           position: getComputedStyle(media.querySelector('.dyn-media-el')).position,
           layer: getComputedStyle(media).willChange };
}"""


@pytest.mark.parametrize("fmt", ["landscape", "portrait"])
async def test_contain_blur_backdrop_is_the_picture_blurred_and_darkened_behind_it(real_app, fmt: str) -> None:
    files = {WIDE_PATH: _still(1600, 1200)}
    media = {"kind": "image", "asset_key": "still-blur", "url": WIDE_PATH, "fit": "contain_blur"}
    served = _timeline(fmt, media)
    async with open_stage(real_app.settings, size=(served["width"], served["height"]), token=TOKEN,
                          base_url=real_app.base, served_timeline=served, frames=files.get) as page:
        await page.seek(2 * FPS)
        got = await page.page.evaluate(_BACKDROP_JS)
        assert page.errors == [] and page.guard_trips == []
    assert got is not None, "no backdrop on the page"
    w, h = got["media"][2], got["media"][3]
    assert got["size"] == [64, round(64 * h / w)], "a small canvas at the laid-out box's aspect"
    assert got["canvas"] == got["media"], "stretched over the whole box"
    assert got["order"] == ["CANVAS", "IMG"] and got["position"] == "relative", "the picture paints above it"
    assert got["layer"] == "auto", "a picture's box is not promoted (Ken Burns scales the picture inside it)"
    assert got["opaque"] == got["pixels"], "drawn edge to edge (the blur never fades into the transparent outside)"
    assert got["hi"] - got["lo"] > 20, "the picture's colours, not a flat fill"
    assert got["hi"] <= 0.6 * 255 + 3, "darkened (brightness 0.6)"
